// src/components/timetable/AutoTimetable.jsx
// ─────────────────────────────────────────────────────────────────────────────
// "Auto-generate timetable": the head teacher picks classes, sets (or asks the
// AI to suggest) how many periods a week each subject gets, previews the
// result and saves it. Lessons are placed by src/services/timetableGenCore.js,
// which checks every teacher across every class, so the result has no clashes;
// anything that can't fit is listed rather than squeezed in. After saving,
// every period stays editable in the grid as before.
// ─────────────────────────────────────────────────────────────────────────────
import { useMemo, useState } from "react";
import { collection, doc, getDocs, query, where, writeBatch, serverTimestamp } from "firebase/firestore";
import { X, Sparkles, Wand2, Save, AlertCircle, CheckCircle, Loader2 } from "lucide-react";
import { db } from "../../firebase";
import { generateTimetable, defaultLoad } from "../../services/timetableGenCore";
import { suggestTimetableLoad } from "../../services/aiTools";

const spin = { animation: "spin 0.65s linear infinite" };
const labelStyle = { fontSize: 11, textTransform: "uppercase", letterSpacing: "0.5px", fontWeight: 600 };

function initialLoads(classes) {
  return Object.fromEntries(classes.map((c) => [c.id, Object.fromEntries((c.subjects || []).map((s) => [s, defaultLoad(s)]))]));
}

export default function AutoTimetable({ schoolCode, classes, staff, allSlots, days, periods, slotId, onSaved, onClose }) {
  const usable = classes.filter((c) => (c.subjects || []).length > 0);
  const [chosen, setChosen] = useState(() => new Set(usable.map((c) => c.id)));
  const [keepExisting, setKeepExisting] = useState(false);
  const [loads, setLoads] = useState(() => initialLoads(usable));
  const [aiBusy, setAiBusy] = useState(false);
  const [aiNote, setAiNote] = useState("");
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);
  const [previewClass, setPreviewClass] = useState(usable[0]?.id || "");
  const [saving, setSaving] = useState(false);

  const capacity = days.length * periods.length;
  const picked = usable.filter((c) => chosen.has(c.id));

  const toggle = (id) => {
    setResult(null);
    setChosen((prev) => { const n = new Set(prev); if (n.has(id)) n.delete(id); else n.add(id); return n; });
  };
  const setCount = (classId, subject, value) => {
    setResult(null);
    setLoads((prev) => ({ ...prev, [classId]: { ...prev[classId], [subject]: Math.max(0, Math.min(10, Number(value) || 0)) } }));
  };

  const askAi = async () => {
    setAiBusy(true);
    setError("");
    const { data, error: err } = await suggestTimetableLoad({
      classes: picked.map((c) => ({ id: c.id, name: c.name, subjects: c.subjects })),
      periodsPerWeek: capacity,
    });
    setAiBusy(false);
    if (err) { setError(`AI suggestion unavailable: ${err} The standard weighting is still filled in.`); return; }
    setResult(null);
    setLoads((prev) => ({ ...prev, ...data.loads }));
    setAiNote(data.note || "Suggested weekly periods filled in. Adjust any number before generating.");
  };

  // Slots of classes not being rebuilt always stay; the chosen classes' own
  // lessons stay only when "keep" is ticked.
  const keep = useMemo(
    () => allSlots.filter((s) => !chosen.has(s.classId) || keepExisting),
    [allSlots, chosen, keepExisting],
  );

  const generate = () => {
    setError("");
    const r = generateTimetable({ classes: picked, teachers: staff, loads, days, periods, keep });
    setResult(r);
    if (!picked.some((c) => c.id === previewClass)) setPreviewClass(picked[0]?.id || "");
  };

  const save = async () => {
    if (!result) return;
    setSaving(true);
    setError("");
    try {
      const writes = [];
      if (!keepExisting) {
        // Clear what the chosen classes had, so the old and new weeks don't mix.
        const snap = await getDocs(query(collection(db, "timetable"), where("schoolCode", "==", schoolCode)));
        snap.docs.filter((d) => chosen.has(d.data().classId)).forEach((d) => writes.push({ del: d.ref }));
      }
      const created = result.slots.map((s) => ({ id: slotId(schoolCode, s.classId, s.day, s.periodNumber), ...s, schoolCode }));
      created.forEach(({ id, ...s }) => writes.push({
        set: doc(db, "timetable", id),
        data: { ...s, autoGenerated: true, createdAt: serverTimestamp(), updatedAt: serverTimestamp() },
      }));
      for (let i = 0; i < writes.length; i += 450) {
        const batch = writeBatch(db);
        writes.slice(i, i + 450).forEach((w) => (w.del ? batch.delete(w.del) : batch.set(w.set, w.data)));
        await batch.commit();
      }
      onSaved([...keep, ...created]);
    } catch (err) {
      console.error("Auto timetable save failed:", err);
      setError(err.code === "permission-denied" ? "Permission denied saving the timetable." : "Could not save the timetable. Please try again.");
      setSaving(false);
    }
  };

  const preview = result?.slots.filter((s) => s.classId === previewClass) || [];
  const cell = (day, n) => preview.find((s) => s.day === day && s.periodNumber === n)
    || (keepExisting ? allSlots.find((s) => s.classId === previewClass && s.day === day && s.periodNumber === n) : null);
  const totalUnplaced = (result?.unplaced || []).reduce((a, u) => a + u.count, 0);

  return (
    <div className="modal-overlay" onClick={(e) => e.target === e.currentTarget && !saving && onClose()}>
      <div className="modal-container" style={{ maxWidth: 920, width: "100%" }}>
        <div className="modal-header">
          <div>
            <h3 style={{ display: "flex", alignItems: "center", gap: 8 }}><Wand2 size={18} /> Auto-generate timetable</h3>
            <p>Uses each class's subjects and the teachers assigned in Staff Management. No teacher is ever booked twice.</p>
          </div>
          <button onClick={onClose} className="modal-close" disabled={saving}><X size={22} /></button>
        </div>

        <div className="modal-body space-y-4" style={{ maxHeight: "70vh", overflowY: "auto" }}>
          {error && <div className="error-message">{error}</div>}

          {usable.length === 0 ? (
            <p className="empty-assignments">No class has subjects yet. Add subjects to the classes first.</p>
          ) : (
            <>
              <div>
                <p className="text-muted" style={labelStyle}>1 · Classes</p>
                <div className="flex gap-2" style={{ flexWrap: "wrap", marginTop: 6 }}>
                  {usable.map((c) => (
                    <button key={c.id} type="button" onClick={() => toggle(c.id)}
                      className={`choice-btn ${chosen.has(c.id) ? "choice-btn--active" : ""}`} style={{ padding: "6px 12px" }}>
                      {c.name}
                    </button>
                  ))}
                </div>
                <label className="flex items-center gap-2" style={{ marginTop: 10, fontSize: 13, cursor: "pointer" }}>
                  <input type="checkbox" checked={keepExisting} onChange={(e) => { setKeepExisting(e.target.checked); setResult(null); }} />
                  Keep the lessons these classes already have and only fill the empty periods
                </label>
              </div>

              <div>
                <div className="flex items-center justify-between" style={{ gap: 12, flexWrap: "wrap" }}>
                  <p className="text-muted" style={labelStyle}>2 · Periods per week ({capacity} available per class)</p>
                  <button type="button" onClick={askAi} disabled={aiBusy || picked.length === 0} className="btn-cancel">
                    {aiBusy ? <Loader2 size={15} style={spin} /> : <Sparkles size={15} />} Suggest with AI
                  </button>
                </div>
                {aiNote && <p className="text-muted" style={{ fontSize: 12.5, marginTop: 6 }}><Sparkles size={12} /> {aiNote}</p>}
                <div className="space-y-2" style={{ marginTop: 8 }}>
                  {picked.map((c) => {
                    const total = Object.values(loads[c.id] || {}).reduce((a, b) => a + b, 0);
                    return (
                      <div key={c.id} style={{ border: "1px solid var(--border-color)", borderRadius: "var(--radius-md)", padding: "8px 10px" }}>
                        <div className="flex justify-between" style={{ fontSize: 12.5, fontWeight: 600, marginBottom: 6 }}>
                          <span>{c.name}</span>
                          <span style={{ color: total > capacity ? "#ef4444" : "var(--text-muted)" }}>
                            {total}/{capacity}{total > capacity ? " (will be trimmed to fit)" : ""}
                          </span>
                        </div>
                        <div className="flex gap-2" style={{ flexWrap: "wrap" }}>
                          {(c.subjects || []).map((s) => (
                            <label key={s} className="flex items-center gap-1" style={{ fontSize: 12, background: "var(--bg-secondary, transparent)", border: "1px dashed var(--border-color)", borderRadius: 6, padding: "2px 6px" }}>
                              {s}
                              <input type="number" min={0} max={10} value={loads[c.id]?.[s] ?? 0}
                                onChange={(e) => setCount(c.id, s, e.target.value)}
                                className="search-input" style={{ width: 52, padding: "2px 6px" }} />
                            </label>
                          ))}
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>

              {result && (
                <div className="space-y-3">
                  <p className="text-muted" style={labelStyle}>3 · Preview</p>
                  <div className={`alert ${totalUnplaced || result.noTeacher.length ? "alert--warning" : "alert--success"}`} style={{ flexDirection: "column", alignItems: "flex-start", gap: 4 }}>
                    <strong style={{ display: "flex", alignItems: "center", gap: 6 }}>
                      {totalUnplaced || result.noTeacher.length ? <AlertCircle size={15} /> : <CheckCircle size={15} />}
                      {result.slots.length} lessons placed with no clashes
                      {totalUnplaced ? `, ${totalUnplaced} couldn't fit` : ""}
                    </strong>
                    {result.noTeacher.slice(0, 6).map((n, i) => (
                      <span key={i} style={{ fontSize: 12.5 }}>No teacher is assigned to {n.subject} in {n.className}. Assign one in Staff Management.</span>
                    ))}
                    {result.noTeacher.length > 6 && <span style={{ fontSize: 12.5 }}>and {result.noTeacher.length - 6} more subjects without a teacher</span>}
                    {result.unplaced.slice(0, 4).map((u, i) => (
                      <span key={`u${i}`} style={{ fontSize: 12.5 }}>{u.className} · {u.subject}: {u.count} period{u.count === 1 ? "" : "s"} left over. {u.reason}</span>
                    ))}
                  </div>
                  <select value={previewClass} onChange={(e) => setPreviewClass(e.target.value)} className="search-input" style={{ width: "auto", minWidth: 180, fontWeight: 600 }}>
                    {picked.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}
                  </select>
                  <div className="data-table-wrap">
                    <table className="data-table" style={{ minWidth: 700 }}>
                      <thead><tr><th style={{ width: 70 }}>Period</th>{days.map((d) => <th key={d}>{d}</th>)}</tr></thead>
                      <tbody>
                        {periods.map((p) => (
                          <tr key={p.number}>
                            <td style={{ fontWeight: 700, fontSize: 12 }}>P{p.number}</td>
                            {days.map((d) => {
                              const s = cell(d, p.number);
                              return (
                                <td key={d} style={{ fontSize: 12 }}>
                                  {s ? <><div style={{ fontWeight: 600 }}>{s.subject}</div><div className="text-muted" style={{ fontSize: 11 }}>{s.teacherName}</div></> : <span className="text-muted">Free</span>}
                                </td>
                              );
                            })}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              )}
            </>
          )}
        </div>

        <div className="modal-footer">
          <button onClick={onClose} className="btn-cancel" disabled={saving}>Cancel</button>
          {result ? (
            <>
              <button onClick={generate} className="btn-cancel" disabled={saving}><Wand2 size={16} /> Regenerate</button>
              <button onClick={save} className="btn-save" disabled={saving || result.slots.length === 0}>
                {saving ? <Loader2 size={16} style={spin} /> : <Save size={16} />}
                {keepExisting ? "Add to timetable" : `Replace ${picked.length} class timetable${picked.length === 1 ? "" : "s"}`}
              </button>
            </>
          ) : (
            <button onClick={generate} className="btn-save" disabled={picked.length === 0}><Wand2 size={16} /> Generate preview</button>
          )}
        </div>
      </div>
    </div>
  );
}
